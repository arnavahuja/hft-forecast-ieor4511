"""T8: the pre-registered robustness trial. Copies the chosen config with label lag 2.

Rule fixed on 2026-11-07, before T7 was run: the source is the trial among T3-T7 with the
highest day-level cross-sectional IC of y_hat in eval_h5m. T8 changes only
labels.start_lag_bars 1 -> 2 (the order fills two minutes after the decision).

usage: make_t8_config.py <source config file name, e.g. config_taq_flow_mlp.yaml>
Writes horizons/h5m/config_t8_lag2.yaml and checks that nothing else differs.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from hft_forecast.ml.config import ExperimentConfig

H5M = Path(__file__).resolve().parents[1]
DEST = H5M / "config_t8_lag2.yaml"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = H5M / sys.argv[1]
    text = src.read_text(encoding="utf-8")
    subs = [
        (r"(?m)^  start_lag_bars: 1\b.*$", "  start_lag_bars: 2      # T8: the only change from the source"),
        (r"(?m)^(name: .*?)( lag1)?\s*$", r"\1 lag2 (T8)"),
        (r"(?m)^tags: \[(.*)\]\s*$", r"tags: [\1, t8]"),
        (r"(?m)^(tags: \[.*)\blag1\b(.*)$", r"\1lag2\2"),
    ]
    for pattern, repl in subs:
        text, n = re.subn(pattern, repl, text, count=1)
        if n != 1:
            sys.exit(f"ERROR: pattern {pattern!r} not found in {src.name}; nothing written")
    header = f"# h5m trial 8 (T8): {src.name} with label lag 2. Generated by scripts/make_t8_config.py.\n"
    DEST.write_text(header + text, encoding="utf-8")
    a, b = ExperimentConfig.load(src), ExperimentConfig.load(DEST)
    skip = {"name", "notes", "tags", "labels"}
    assert a.model_dump(mode="json", exclude=skip) == b.model_dump(mode="json", exclude=skip)
    la, lb = a.labels.model_dump(), b.labels.model_dump()
    assert (la.pop("start_lag_bars"), lb.pop("start_lag_bars")) == (1, 2) and la == lb
    print(f"wrote {DEST.name} from {src.name}: only labels.start_lag_bars differs (1 -> 2)")


if __name__ == "__main__":
    main()
