"""Write the 2024H2 holdout copies of h5m configs: same settings, only the period changes.

usage (repository root):
    python backend/hft_forecast/ml/horizons/h5m/scripts/make_holdout_configs.py config_taq_lag1.yaml ...

For each config it writes horizons/h5m/holdout/<same file name> with
    experiment: h5m_holdout      (a separate trial register: the holdout is not research)
    start/end:  2024-07-01 / 2024-12-31
and everything else byte-for-byte unchanged. The holdout runs read
HFTF_DATA_DIR=E:\\4511_5min\\wrds_taq_h2, so they never touch the research folder.
A check at the end proves that only experiment, name, tags and the dates differ.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from hft_forecast.ml.config import ExperimentConfig

H5M = Path(__file__).resolve().parents[1]
OUT = H5M / "holdout"


def convert(text: str) -> str:
    subs = [
        (r"(?m)^experiment: h5m\s*$", "experiment: h5m_holdout"),
        (r"(?m)^(name: .*)$", r"\1 [holdout 2024H2]"),
        (r"(?m)^  start: 2024-01-02\s*$", "  start: 2024-07-01"),
        (r"(?m)^  end: 2024-06-28.*$", "  end: 2024-12-31     # holdout: 2024H2, run once"),
        (r"(?m)^tags: \[(.*)\]\s*$", r"tags: [\1, holdout]"),
    ]
    for pattern, repl in subs:
        text, n = re.subn(pattern, repl, text)
        if n != 1:
            sys.exit(f"ERROR: pattern {pattern!r} matched {n} times; nothing written for this file")
    header = "# HOLDOUT copy, generated by scripts/make_holdout_configs.py. Do not edit by hand.\n"
    return header + text


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    OUT.mkdir(exist_ok=True)
    keep = {"name", "notes", "tags", "experiment", "data"}
    for name in sys.argv[1:]:
        src = H5M / name
        dest = OUT / name
        dest.write_text(convert(src.read_text(encoding="utf-8")), encoding="utf-8")
        a, b = ExperimentConfig.load(src), ExperimentConfig.load(dest)
        assert a.model_dump(mode="json", exclude=keep) == b.model_dump(mode="json", exclude=keep)
        da, db = a.data.model_dump(mode="json"), b.data.model_dump(mode="json")
        assert {k for k in da if da[k] != db[k]} == {"start", "end"}, (da, db)
        assert b.experiment == "h5m_holdout" and str(b.data.start) == "2024-07-01"
        print(f"wrote {dest.relative_to(H5M)}  (only experiment, name, tags and dates differ)")


if __name__ == "__main__":
    main()
